export const SERVICE_BY_ID = new Map(SERVICE_TYPES.map((s) => [s.id, s]));

/** Adds (or refreshes) a service type generated by research. Ids are unique per civilization. */
export function registerServiceType(st: ServiceType): void {
  SERVICE_BY_ID.set(st.id, st);
}

