import type { ProceduralStyle, ServiceStyle } from '../buildings/Archetypes';

export type CoverageKind = 'police' | 'fire' | 'health' | 'education' | 'garbage' | 'park';
export type UtilityKind = 'power' | 'water' | 'sewage';
export type ServiceKind = CoverageKind | UtilityKind | 'transit' | 'landmark' | 'research';
export type ServiceCategory = 'services' | 'utilities' | 'parks' | 'transit' | 'landmarks';

export interface ServiceType {
  id: string;
  name: string;
  description: string;
  kind: ServiceKind;
  category: ServiceCategory;
  style: ServiceStyle | ProceduralStyle;
  cost: number;
  /** Monthly upkeep. */
  upkeep: number;
  /** Coverage radius in meters (coverage services and parks). */
  radius: number;
  /** Residents served at full effectiveness (coverage), or garbage units/day processed. */
  capacity: number;
  /** Utility output: MW for power, m³/day for water and sewage. */
  output: number;
  w: number;
  d: number;
  jobs: number;
  /** Ground pollution emitted (0–1 scale). */
  pollution: number;
  /** Land value bonus applied within radius (parks). */
  attractiveness: number;
  needsShore: boolean;
  unlockPopulation: number;
  /** Monthly tourism income at full city happiness (landmarks). */
  tourism: number;
  /** Only one may be built. */
  unique: boolean;
  /** Energy storage (MW it can deliver from stored surplus). */
  storage?: number;
  /** Generated by this civilization's research (the design behind it). */
  designId?: string;
}

function svc(t: Partial<ServiceType> & Pick<ServiceType, 'id' | 'name' | 'description' | 'kind' | 'category' | 'style' | 'cost' | 'upkeep' | 'w' | 'd'>): ServiceType {
  return {
    radius: 0,
    capacity: 0,
    output: 0,
    jobs: 0,
    pollution: 0,
    attractiveness: 0,
    needsShore: false,
    unlockPopulation: 0,
    tourism: 0,
    unique: false,
    ...t,
  };
}

